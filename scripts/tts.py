async def main():
    durations = {}
    for name, text in SEGMENTS:
        path = os.path.join(OUT, f"{name}.mp3")
        communicate = edge_tts.Communicate(text, VOICE, rate="-6%")
        await communicate.save(path)
        durations[name] = os.path.getsize(path)
        print(name, "chars", len(text), "bytes", os.path.getsize(path))
    with open(os.path.join(OUT, "meta.json"), "w", encoding="utf-8") as f:
        json.dump({"voice": VOICE, "segments": [s[0] for s in SEGMENTS]}, f, ensure_ascii=False)


asyncio.run(main())
